#!/usr/bin/env python3
"""Write rustsocket/src/vectors68k.c: rustsocket.library's 68k jump
table (CreateLibrary's CLT_Vector68K), so 68k programs can call it as they
call Roadshow (IBrowse 2, identd and other 68k network programs).

Each 68k LVO is an EmuTrap into a PPC stub that takes the arguments from
the 68k registers named by the SDK's netinclude/pragmas/bsdsocket_pragmas.h
("libcall SocketBase socket 01e 21003": offset 0x1e; the last digit is the
argument count, the one before it the result register, the digits before
that the argument registers read right to left, 0-7 d0-d7, 8-f a0-a7) and
calls the calling task's own "main" interface (rs68k_iface in
library_glue.c: one per 68k task, made at its 68k OpenLibrary) through the
slot the crate's SocketIFace binding gives the same name. Entries 0-3 are
Open, Close, Expunge and the reserved one (library_glue.c).

It fails by name on a pragma whose name the interface does not have, on a
register spec it cannot read, and on an argument count above 8; a gap in
the offsets gets a stub that returns -1.

Run from the VirtioRust root with the pragmas file taken from the SDK:
    python3 tools/gen-socket-vectors68k.py <path>/bsdsocket_pragmas.h
(the os4-gcc11 image: /opt/ppc-amigaos/ppc-amigaos/SDK/include/netinclude/
pragmas/bsdsocket_pragmas.h).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BINDING = os.path.join(ROOT, "amigaos4", "src", "sys", "interfaces", "bsdsocket.rs")
OUT = os.path.join(ROOT, "rustsocket", "src", "vectors68k.c")
REGS = ["D0", "D1", "D2", "D3", "D4", "D5", "D6", "D7", "A0", "A1", "A2", "A3", "A4", "A5", "A6", "A7"]

if len(sys.argv) != 2:
    sys.exit("usage: gen-socket-vectors68k.py <bsdsocket_pragmas.h>")

# The PPC interface's slots and their kinds.
text = open(BINDING, encoding="utf-8").read()
body = text[text.index("pub struct SocketIFace"):]
body = body[:body.index("\n}")]
slots = {}
for m in re.finditer(r"pub (\w+): (.*?), // (\d+): (\d+)", body):
    slots[m.group(1)] = (int(m.group(3)), m.group(2))


def kind(ty):
    m = re.search(r"\)\s*->\s*(.+)$", ty)
    if not m:
        return "void"
    r = m.group(1).strip()
    return "ptr" if r.startswith("*") or r in ("APTR", "STRPTR", "CONST_STRPTR") else "num"


calls = {}
src = open(sys.argv[1], encoding="latin-1").read()
for m in re.finditer(r"^#pragma\s+libcall\s+SocketBase\s+(\w+)\s+([0-9a-fA-F]+)\s+([0-9a-fA-F]+)\s*$", src, re.M):
    name, off, spec = m.group(1), int(m.group(2), 16), m.group(3).lower()
    n = int(spec[-1], 16)
    if len(spec) != n + 2 or spec[-2] != "0" or n > 8:
        sys.exit("cannot read the register spec %s of %s" % (spec, name))
    args = [REGS[int(c, 16)] for c in reversed(spec[:-2])]
    if name not in slots:
        sys.exit("%s: no such slot in the SocketIFace binding" % name)
    if off in calls and calls[off][0] != name:
        sys.exit("offset 0x%x named twice (%s, %s)" % (off, calls[off][0], name))
    calls[off] = (name, args)

first = 0x1e
last = max(calls)
out = []
out.append("/* Generated by tools/gen-socket-vectors68k.py from the SDK's")
out.append("   netinclude/pragmas/bsdsocket_pragmas.h and the crate's SocketIFace")
out.append("   binding. Do not edit. */")
out.append("")
out.append("#include <exec/types.h>")
out.append("#include <exec/interfaces.h>")
out.append("#include <exec/emulation.h>")
out.append("")
out.append("extern uint32 rs68k_open(uint32 *regs);")
out.append("extern uint32 rs68k_close(uint32 *regs);")
out.append("extern uint32 rs68k_expunge(uint32 *regs);")
out.append("extern uint32 rs68k_reserved(uint32 *regs);")
out.append("extern struct Interface *rs68k_iface(void);")
out.append("")
out.append("#define R(r) regs[REG68K_##r / 4]")
out.append("#define SLOT(i, n) (((void **)((uint8 *)(i) + 60))[n])")
out.append("")
for name, fn in (("open", "rs68k_open"), ("close", "rs68k_close"), ("expunge", "rs68k_expunge"), ("reserved", "rs68k_reserved")):
    out.append("static const struct EmuTrap trap_%s = { TRAPINST, TRAPTYPE, %s };" % (name, fn))
out.append("")
entries = ["&trap_open", "&trap_close", "&trap_expunge", "&trap_reserved"]
gap_used = False
for off in range(first, last + 1, 6):
    if off not in calls:
        gap_used = True
        entries.append("&trap_gap")
        continue
    name, args = calls[off]
    slot, ty = slots[name]
    k = kind(ty)
    fail = {"num": "(uint32)-1", "ptr": "0", "void": "0"}[k]
    params = ", ".join(["struct Interface *"] + ["uint32"] * len(args))
    call_args = ", ".join(["i"] + ["R(%s)" % a for a in args])
    out.append("/* 0x%03x: %s(%s) -> slot %d */" % (off, name, ", ".join(a.lower() for a in args), slot))
    out.append("static uint32 stub_%s(uint32 *regs)" % name)
    out.append("{")
    out.append("    struct Interface *i = rs68k_iface();")
    out.append("    if (!i) return %s;" % fail)
    if k == "void":
        out.append("    ((void (*)(%s))SLOT(i, %d))(%s);" % (params, slot, call_args))
        out.append("    return 0;")
    else:
        out.append("    return (uint32)((uint32 (*)(%s))SLOT(i, %d))(%s);" % (params, slot, call_args))
    out.append("}")
    out.append("static const struct EmuTrap trap_%s = { TRAPINST, %s, stub_%s };" % (name, "TRAPTYPENR" if k == "void" else "TRAPTYPE", name))
    out.append("")
    entries.append("&trap_%s" % name)
if gap_used:
    out.insert(out.index("#define R(r) regs[REG68K_##r / 4]"), "static uint32 stub_gap(uint32 *regs) { (void)regs; return (uint32)-1; }\nstatic const struct EmuTrap trap_gap = { TRAPINST, TRAPTYPE, stub_gap };\n")
out.append("/* The 68k jump table: LVO -6 (Open) first, one entry per 6 bytes. */")
out.append("const APTR VecTable68K[] = {")
for e in entries:
    out.append("    (APTR)%s," % e)
out.append("    (APTR)-1")
out.append("};")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote %s: %d 68k entries (%d calls, offsets 0x1e..0x%x)" % (OUT, len(entries), len(calls), last))
